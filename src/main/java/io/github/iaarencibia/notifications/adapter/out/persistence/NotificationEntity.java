package io.github.iaarencibia.notifications.adapter.out.persistence;

import io.github.iaarencibia.notifications.domain.Channel;
import io.github.iaarencibia.notifications.domain.NotificationStatus;
import io.github.iaarencibia.notifications.domain.Priority;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.Instant;
import java.util.Map;
import java.util.UUID;

/**
 * The row, as JPA sees it. It carries no behaviour: every rule lives in the aggregate, and this
 * exists so that the aggregate never has to know what a table is.
 *
 * <p>Two columns are deliberately absent. {@code priority_rank} is generated by the database and
 * would only be written back wrong from here. {@code version} is the optimistic lock, and belongs
 * to the dispatcher -- it is the only writer that holds an aggregate across a network call.
 */
@Entity
@Table(name = "notification")
class NotificationEntity {

    @Id
    private UUID id;

    private String recipient;

    @Enumerated(EnumType.STRING)
    private Channel channel;

    private String subject;

    private String body;

    @Enumerated(EnumType.STRING)
    private Priority priority;

    /** Arbitrary client data, stored as JSONB and handed back untouched. */
    @JdbcTypeCode(SqlTypes.JSON)
    private Map<String, String> metadata;

    @Enumerated(EnumType.STRING)
    private NotificationStatus status;

    private int attempts;

    @Column(name = "max_attempts")
    private int maxAttempts;

    @Column(name = "next_attempt_at")
    private Instant nextAttemptAt;

    @Column(name = "last_error")
    private String lastError;

    @Column(name = "claimed_at")
    private Instant claimedAt;

    @Column(name = "claimed_by")
    private String claimedBy;

    @Column(name = "correlation_id")
    private String correlationId;

    @Column(name = "idempotency_key")
    private String idempotencyKey;

    @Column(name = "created_at")
    private Instant createdAt;

    @Column(name = "updated_at")
    private Instant updatedAt;

    @Column(name = "sent_at")
    private Instant sentAt;

    protected NotificationEntity() {
        // Required by JPA.
    }

    NotificationEntity(UUID id, String recipient, Channel channel, String subject, String body,
            Priority priority, Map<String, String> metadata, NotificationStatus status,
            int attempts, int maxAttempts, Instant nextAttemptAt, String lastError,
            Instant claimedAt, String claimedBy, String correlationId, String idempotencyKey,
            Instant createdAt, Instant updatedAt, Instant sentAt) {
        this.id = id;
        this.recipient = recipient;
        this.channel = channel;
        this.subject = subject;
        this.body = body;
        this.priority = priority;
        this.metadata = metadata;
        this.status = status;
        this.attempts = attempts;
        this.maxAttempts = maxAttempts;
        this.nextAttemptAt = nextAttemptAt;
        this.lastError = lastError;
        this.claimedAt = claimedAt;
        this.claimedBy = claimedBy;
        this.correlationId = correlationId;
        this.idempotencyKey = idempotencyKey;
        this.createdAt = createdAt;
        this.updatedAt = updatedAt;
        this.sentAt = sentAt;
    }

    UUID getId() {
        return id;
    }

    String getRecipient() {
        return recipient;
    }

    Channel getChannel() {
        return channel;
    }

    String getSubject() {
        return subject;
    }

    String getBody() {
        return body;
    }

    Priority getPriority() {
        return priority;
    }

    Map<String, String> getMetadata() {
        return metadata;
    }

    NotificationStatus getStatus() {
        return status;
    }

    int getAttempts() {
        return attempts;
    }

    int getMaxAttempts() {
        return maxAttempts;
    }

    Instant getNextAttemptAt() {
        return nextAttemptAt;
    }

    String getLastError() {
        return lastError;
    }

    Instant getClaimedAt() {
        return claimedAt;
    }

    String getClaimedBy() {
        return claimedBy;
    }

    String getCorrelationId() {
        return correlationId;
    }

    String getIdempotencyKey() {
        return idempotencyKey;
    }

    Instant getCreatedAt() {
        return createdAt;
    }

    Instant getUpdatedAt() {
        return updatedAt;
    }

    Instant getSentAt() {
        return sentAt;
    }
}
